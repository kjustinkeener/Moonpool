// 16-slot categorical color sets, one per theme id. Each set is a 16-element
// tuple indexed 0..15 in the canonical ANSI/xterm slot ORDER (0 black, 1 red,
// 2 green, 3 yellow, 4 blue, 5 magenta, 6 cyan, 7 white, then 8..15 the bright
// eight). The set is a per-theme CATEGORICAL palette (log levels, syntax, diff
// add/remove, chart series, tag/badge colors: eight hues x two intensities).
//
// Slots are addressed by INDEX, not name: after per-theme tuning a slot's hue
// may not match its ANSI name (e.g. dark's slot 3 holds the app's orange, slot
// 13 holds pink), so the names would lie - the index is the honest handle. The
// generator still derives slots from each theme's --red/--green/... internally
// (below); the slot NAMES survive only as the fixed emit ORDER.
//
// Sets marked "hand-tuned" were authored by eye (Moonpool). The rest are
// generated by tools/gen-ansi.py from each theme's own palette in themes.css
// and contrast-checked against that theme's ground; regenerate with:
//     python tools/gen-ansi.py
// Editing a generated set by hand is fine - add its id to HAND_TUNED in the
// script so a later run preserves it.
