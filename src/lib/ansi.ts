// Resolve a color set for a RESOLVED theme id (never "auto"); falls back to
// dark, so a theme with no set of its own still renders.
export function ansiFor(id: string): AnsiPalette {
  return ANSI[id] ?? ANSI.dark;
}

// The same set under xterm's named ITheme color slots (xterm wants keys, not an
// index). Spread into the terminal theme: `{ ...xtermColors(id) }`.
const XTERM_SLOTS = [
  "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
  "brightBlack", "brightRed", "brightGreen", "brightYellow",
  "brightBlue", "brightMagenta", "brightCyan", "brightWhite",
] as const;

export function xtermColors(id: string): Record<(typeof XTERM_SLOTS)[number], string> {
  const set = ansiFor(id);
  return Object.fromEntries(XTERM_SLOTS.map((k, i) => [k, set[i]])) as Record<
    (typeof XTERM_SLOTS)[number],
    string
  >;
}
